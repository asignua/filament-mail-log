<?php

declare(strict_types=1);

namespace Asignua\FilamentMailLog\Tests\Webhooks;

use Asignua\FilamentMailLog\Enums\BounceType;
use Asignua\FilamentMailLog\Enums\DeliveryEventType;
use Asignua\FilamentMailLog\Enums\DeliveryStatus;
use Asignua\FilamentMailLog\Models\MailSuppression;
use Illuminate\Http\Client\Request;
use Illuminate\Support\Facades\Http;

/**
 * Payload shapes: "Amazon SES event publishing / notification contents" (Bounce, Complaint, Delivery, Open, Click)
 * wrapped in the SNS HTTP message format (Notification, SubscriptionConfirmation) with the documented signing rules.
 * The signing certificate here is generated by the test and "served" through Http::fake.
 */
class SesWebhookTest extends WebhookTestCase
{
    private const string TOPIC = 'arn:aws:sns:eu-west-1:123456789012:ses-events';

    private const string CERT_URL = 'https://sns.eu-west-1.amazonaws.com/SimpleNotificationService-0000000000000000000000.pem';

    private const string SUBSCRIBE_URL = 'https://sns.eu-west-1.amazonaws.com/?Action=ConfirmSubscription&TopicArn=arn:aws:sns:eu-west-1:123456789012:ses-events&Token=2336412f37fb687f5d51e6e2';

    /** @var \OpenSSLAsymmetricKey */
    private $private;

    private int $confirmStatus = 200;

    protected function provider(): string
    {
        return 'ses';
    }

    protected function setUp(): void
    {
        parent::setUp();

        $key = openssl_pkey_new(['private_key_bits' => 2048, 'private_key_type' => OPENSSL_KEYTYPE_RSA]);
        $this->assertNotFalse($key);
        $this->private = $key;

        $pem = $this->certificate($key, 'sns.amazonaws.com', 'Amazon');

        Http::fake([
            self::CERT_URL => Http::response($pem),
            'https://sns.eu-west-1.amazonaws.com/?Action=ConfirmSubscription*' => fn () => Http::response('<ConfirmSubscriptionResponse/>', $this->confirmStatus),
        ]);

        $this->enable('ses', ['topic_arns' => [self::TOPIC]]);
    }

    private function certificate(\OpenSSLAsymmetricKey $key, string $commonName, string $organization): string
    {
        $csr = openssl_csr_new(['commonName' => $commonName, 'organizationName' => $organization], $key);
        $this->assertNotFalse($csr);
        $certificate = openssl_csr_sign($csr, null, $key, 1);
        openssl_x509_export($certificate, $pem);

        return $pem;
    }

    /**
     * @param array<string, mixed> $message
     * @param array<string, mixed> $overrides fields set AFTER signing, to forge a message
     */
    private function sns(array $message, string $type = 'Notification', int $version = 2, array $overrides = [], ?int $age = null): string
    {
        $fields = $message + [
            'Type' => $type,
            'MessageId' => '22b80b92-fdea-4c2c-8f9d-bdfb0c7bf324',
            'TopicArn' => self::TOPIC,
            'Timestamp' => gmdate('Y-m-d\TH:i:s.000\Z', time() - ($age ?? 0)),
            'SignatureVersion' => (string) $version,
            'SigningCertURL' => self::CERT_URL,
        ];

        $keys = $type === 'Notification'
            ? ['Message', 'MessageId', 'Subject', 'Timestamp', 'TopicArn', 'Type']
            : ['Message', 'MessageId', 'SubscribeURL', 'Timestamp', 'Token', 'TopicArn', 'Type'];
        $canonical = '';

        foreach ($keys as $key) {
            if (isset($fields[$key])) {
                $canonical .= $key."\n".$fields[$key]."\n";
            }
        }

        openssl_sign($canonical, $signature, $this->private, $version === 1 ? OPENSSL_ALGO_SHA1 : OPENSSL_ALGO_SHA256);
        $fields['Signature'] = base64_encode($signature);

        return (string) json_encode($overrides + $fields);
    }

    /**
     * @param array<string, mixed> $event
     */
    private function notification(array $event, string $type = 'Notification', array $overrides = []): string
    {
        return $this->sns(['Message' => (string) json_encode($event)], $type, 2, $overrides);
    }

    /**
     * @return array<string, mixed>
     */
    private function mail(array $extra = []): array
    {
        return $extra + [
            'timestamp' => '2026-10-23T00:40:02.012Z',
            'source' => 'Sender Name <sender@example.com>',
            'messageId' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000',
            'destination' => ['Recipient@Example.com'],
            'headersTruncated' => false,
            'commonHeaders' => ['from' => ['Sender Name <sender@example.com>'], 'to' => ['recipient@example.com'], 'subject' => 'Message sent from Amazon SES'],
            'tags' => ['ses:configuration-set' => ['ConfigSet'], 'ses:source-ip' => ['192.0.2.0']],
        ];
    }

    public function test_it_is_off_until_enabled(): void
    {
        config()->set('filament-mail-log.webhooks.providers.ses.enabled', false);

        $this->hook($this->notification(['eventType' => 'Delivery', 'mail' => $this->mail()]))->assertNotFound();
    }

    public function test_a_delivery_is_matched_by_the_ses_message_id(): void
    {
        $log = $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);

        $this->hook($this->notification([
            'eventType' => 'Delivery',
            'mail' => $this->mail(),
            'delivery' => ['timestamp' => '2026-10-23T00:41:02.669Z', 'processingTimeMillis' => 546, 'recipients' => ['recipient@example.com'], 'smtpResponse' => '250 ok:  Message 64111812 accepted', 'reportingMTA' => 'a8-70.smtp-out.amazonses.com'],
        ]))->assertOk()->assertJson(['received' => 1, 'matched' => 1]);

        $event = $this->events()->sole();
        $this->assertSame($log->getKey(), $event->mail_log_id);
        $this->assertSame(DeliveryEventType::Delivered, $event->type);
        $this->assertSame('recipient@example.com', $event->recipient);
        $this->assertSame('250 ok:  Message 64111812 accepted', $event->detail);
        $this->assertSame(DeliveryStatus::Delivered, $log->fresh()->delivery_status);
    }

    public function test_the_signature_version_1_with_sha1_is_accepted(): void
    {
        $log = $this->log(['message_id' => 'abc']);
        $body = $this->sns(['Message' => (string) json_encode(['eventType' => 'Delivery', 'mail' => $this->mail(['messageId' => 'abc']), 'delivery' => ['recipients' => ['recipient@example.com']]])], 'Notification', 1);

        $this->hook($body)->assertOk()->assertJson(['matched' => 1]);

        $this->assertSame(DeliveryStatus::Delivered, $log->fresh()->delivery_status);
    }

    public function test_it_is_matched_by_the_tag_and_by_the_echoed_header(): void
    {
        $byTag = $this->log();
        $byHeader = $this->log();

        $this->hook($this->notification(['eventType' => 'Open', 'mail' => $this->mail(['messageId' => 'x1', 'tags' => ['mail_log_id' => [$byTag->ulid]]]), 'open' => ['timestamp' => '2026-10-23T01:00:00Z']]))->assertOk();

        $headers = [['name' => 'From', 'value' => 'sender@example.com'], ['name' => 'X-Mail-Log-Id', 'value' => $byHeader->ulid]];
        $this->hook($this->sns(['MessageId' => 'sns-2', 'Message' => (string) json_encode(['eventType' => 'Click', 'mail' => $this->mail(['messageId' => 'x2', 'headers' => $headers]), 'click' => ['timestamp' => '2026-10-23T01:01:00Z', 'link' => 'https://example.test/?token=zzz']])]))->assertOk();

        $this->assertSame([$byTag->getKey(), $byHeader->getKey()], $this->events()->pluck('mail_log_id')->all());
        $this->assertSame(DeliveryStatus::Opened, $byTag->fresh()->delivery_status);
        $this->assertSame(DeliveryStatus::Clicked, $byHeader->fresh()->delivery_status);
    }

    public function test_a_permanent_bounce_suppresses_every_bounced_recipient(): void
    {
        $log = $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);

        $this->hook($this->notification([
            'eventType' => 'Bounce',
            'bounce' => [
                'feedbackId' => '0100018bexample-feedback-000000',
                'bounceType' => 'Permanent',
                'bounceSubType' => 'General',
                'bouncedRecipients' => [
                    ['emailAddress' => 'Recipient@Example.com', 'action' => 'failed', 'status' => '5.1.1', 'diagnosticCode' => 'smtp; 550 5.1.1 user unknown'],
                    ['emailAddress' => 'second@example.com', 'action' => 'failed', 'status' => '5.1.1'],
                ],
                'timestamp' => '2026-10-23T00:41:02.669Z',
                'reportingMTA' => 'dsn; mta.example.com',
            ],
            'mail' => $this->mail(),
        ]))->assertOk();

        $this->assertSame(2, $this->events()->count());
        $this->assertSame(BounceType::Hard, $this->events()->first()->bounce);
        $this->assertSame('smtp; 550 5.1.1 user unknown', $this->events()->first()->detail);
        $this->assertSame(DeliveryStatus::Bounced, $log->fresh()->delivery_status);
        $this->assertEqualsCanonicalizing(['recipient@example.com', 'second@example.com'], MailSuppression::query()->pluck('email')->all());
    }

    public function test_a_transient_bounce_is_soft(): void
    {
        $log = $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);

        $this->hook($this->notification([
            'eventType' => 'Bounce',
            'bounce' => ['bounceType' => 'Transient', 'bounceSubType' => 'MailboxFull', 'bouncedRecipients' => [['emailAddress' => 'recipient@example.com']], 'timestamp' => '2026-10-23T00:41:02.669Z'],
            'mail' => $this->mail(),
        ]))->assertOk();

        $this->assertSame(DeliveryStatus::SoftBounced, $log->fresh()->delivery_status);
        $this->assertSame(0, MailSuppression::query()->count());
    }

    public function test_a_complaint_with_the_legacy_notification_type(): void
    {
        $log = $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);

        $this->hook($this->notification([
            'notificationType' => 'Complaint',
            'complaint' => ['complainedRecipients' => [['emailAddress' => 'recipient@example.com']], 'timestamp' => '2026-10-23T00:41:02.669Z', 'feedbackId' => 'f1', 'complaintFeedbackType' => 'abuse'],
            'mail' => $this->mail(),
        ]))->assertOk();

        $this->assertSame(DeliveryStatus::Complained, $log->fresh()->delivery_status);
        $this->assertSame('complaint', MailSuppression::query()->sole()->reason->value);
    }

    public function test_reject_delay_and_untracked_events(): void
    {
        $log = $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);

        $this->hook($this->sns(['MessageId' => 'a', 'Message' => (string) json_encode(['eventType' => 'DeliveryDelay', 'mail' => $this->mail(), 'deliveryDelay' => ['delayType' => 'MailboxFull', 'delayedRecipients' => [['emailAddress' => 'recipient@example.com', 'status' => '4.4.1', 'diagnosticCode' => 'smtp; 421 timeout']], 'timestamp' => '2026-10-23T00:41:02Z']])]))->assertOk();
        $this->hook($this->sns(['MessageId' => 'b', 'Message' => (string) json_encode(['eventType' => 'Reject', 'mail' => $this->mail(), 'reject' => ['reason' => 'Bad content']])]))->assertOk();
        $this->hook($this->sns(['MessageId' => 'c', 'Message' => (string) json_encode(['eventType' => 'Send', 'mail' => $this->mail()])]))->assertOk()->assertJson(['received' => 0]);
        $this->hook($this->sns(['MessageId' => 'd', 'Message' => 'a plain text test message']))->assertOk()->assertJson(['received' => 0]);

        $this->assertSame([DeliveryEventType::Deferred, DeliveryEventType::Rejected], $this->events()->pluck('type')->all());
        $this->assertSame(DeliveryStatus::Rejected, $log->fresh()->delivery_status);
    }

    public function test_a_redelivered_notification_is_stored_once(): void
    {
        $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);
        $body = $this->notification(['eventType' => 'Delivery', 'mail' => $this->mail(), 'delivery' => ['recipients' => ['recipient@example.com']]]);

        $this->hook($body)->assertOk();
        $this->hook($body)->assertOk();

        $this->assertCount(1, $this->events());
    }

    public function test_a_forged_or_unsigned_message_is_refused(): void
    {
        $this->log(['message_id' => '0100018bexample-aedb9a-02f9-4d12-a87d-dd0099a07f8a-000000']);
        $event = ['eventType' => 'Delivery', 'mail' => $this->mail(), 'delivery' => ['recipients' => ['recipient@example.com']]];

        // The Message was changed after signing.
        $this->hook($this->notification($event, 'Notification', ['Message' => (string) json_encode(['eventType' => 'Complaint'] + $event)]))->assertForbidden();
        // No signature at all.
        $this->hook((string) json_encode(['Type' => 'Notification', 'TopicArn' => self::TOPIC, 'Message' => (string) json_encode($event), 'MessageId' => '1', 'Timestamp' => gmdate('c')]))->assertForbidden();
        // An unknown signature version.
        $this->hook($this->sns(['Message' => (string) json_encode($event)], 'Notification', 3))->assertForbidden();
        $this->hook('{"x"')->assertForbidden();

        $this->assertCount(0, $this->events());
    }

    public function test_a_validly_signed_message_from_another_topic_is_refused(): void
